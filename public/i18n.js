// First preferred browser language that we support wins; English is the fallback.
export function detectLang(search = globalThis.location?.search || '', languages = globalThis.navigator?.languages || []) {
  const forced = new URLSearchParams(search).get('lang');
  if (forced && STRINGS[forced]) return forced;
  for (const l of languages) {
    const base = String(l).toLowerCase().split('-')[0];
    if (STRINGS[base]) return base;
  }
  return 'en';
}

export const lang = detectLang();

export function t(key, params = {}, language = lang) {
  const s = (STRINGS[language] && STRINGS[language][key]) ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
}

